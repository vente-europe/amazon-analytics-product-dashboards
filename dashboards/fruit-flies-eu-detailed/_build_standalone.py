# -*- coding: utf-8 -*-
"""Build standalone index.html for the Fruit Flies EU (Detailed) dashboard.

THREE-tab standalone, Polish UI, NO product segment (pack-size structure instead):
  Tab 1 · Rynek           - cross-market topline (generated by _build_rynek.py)
  Tab 2 · Struktura rynku - pack-size x brand market structure per country
                            (generated by _build_structure.py), modelled on the
                            fruit-fly-trap-DE dashboard's Market Structure tab.
  Tab 3 · Recenzje (VOC)  - UK-only Voice-of-Customer (generated by _build_voc.py),
                            reuses the u-reviews-voc template + provecta's Polish
                            transform. Only UK has scraped reviews.

Markets: FR / IT / ES / UK. All EUR (UK GBP converted upstream in _consolidate.py).
12M projection uses the German seasonality multiplier (~x7.90, July export).

Pipeline:
  1. Run _build_rynek.py     -> _rynek_topline.html   (tab 1 body)
  2. Run _build_structure.py -> _structure.html       (tab 2 fragment)
  3. Run _build_voc.py       -> _voc.html             (tab 3 fragment, UK only)
  4. Assemble the ad-* shell (header + 3-tab bar + 3 panels) -> index.html.
     Tabs 2 & 3 render lazily the first time opened (canvas must be visible to
     size correctly) via window.__structRender() / window.__vocRender().

Run (Windows):
    python _build_standalone.py
"""
import os, re, sys, subprocess

try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass

BASE = os.path.dirname(os.path.abspath(__file__))
RYNEK_HTML = os.path.join(BASE, '_rynek_topline.html')
STRUCT_HTML = os.path.join(BASE, '_structure.html')
VOC_HTML = os.path.join(BASE, '_voc.html')
VOC_STICKY_HTML = os.path.join(BASE, '_voc_sticky.html')

# ── Identity ────────────────────────────────────────────────────────────────
PRODUCT_TITLE = 'Fruit Flies EU - Detailed (FR, IT, ES, UK)'
DASHBOARD_H2  = 'Fruit Flies EU - Analiza szczegółowa'
DASHBOARD_SUB = 'Rynki: Francja · Włochy · Hiszpania · Wielka Brytania · Dane: Helium 10 X-Ray (projekcja 30d z sezonowością rynku DE, EUR)'

XRAY_LINKS = {'FR': '#', 'IT': '#', 'ES': '#', 'UK': '#'}
