# ── 1-2. Regenerate both tab sources ────────────────────────────────────────
print('Running _build_seasonality.py ...')
subprocess.run([sys.executable, os.path.join(BASE, '_build_seasonality.py')], check=True)
print('Running _build_rynek.py ...')
subprocess.run([sys.executable, os.path.join(BASE, '_build_rynek.py')], check=True)
print('Running _build_structure.py ...')
subprocess.run([sys.executable, os.path.join(BASE, '_build_structure.py')], check=True)
print('Running _build_voc.py ...')
subprocess.run([sys.executable, os.path.join(BASE, '_build_voc.py')], check=True)
print('Running _build_voc_sticky.py ...')
subprocess.run([sys.executable, os.path.join(BASE, '_build_voc_sticky.py')], check=True)

rynek = open(RYNEK_HTML, encoding='utf-8').read()
m_style = re.search(r'<style>(.*?)</style>', rynek, re.S)
m_body  = re.search(r'<body>(.*?)</body>', rynek, re.S)
if not m_style or not m_body:
    raise SystemExit('could not extract <style>/<body> from _rynek_topline.html')
topline_css  = m_style.group(1)
topline_body = re.sub(r'<header>.*?</header>', '', m_body.group(1), flags=re.S)

structure_body = open(STRUCT_HTML, encoding='utf-8').read()
voc_body = open(VOC_HTML, encoding='utf-8').read()
voc_sticky_body = open(VOC_STICKY_HTML, encoding='utf-8').read()

# ── X-Ray buttons (only real links) ─────────────────────────────────────────
xray_buttons = ''
for code, href in XRAY_LINKS.items():
    if href and href != '#':
        xray_buttons += (
            f'<a class="ad-xray-btn" href="{href}" target="_blank" rel="noopener">'
            f'<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">'
            f'<path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/>'
            f'<polyline points="14 2 14 8 20 8"/></svg>{FLAG.get(code, "")} {code} X-Ray</a>'
        )

